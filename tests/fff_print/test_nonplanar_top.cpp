        const bool            upright = (frame * Vec3d::UnitZ()).normalized().z() > 1. - 1e-9;
        const size_t shells = scan_layers(*obj, [](double, double) { return 0.; }, [](double, double) { return true; }, 4 * kH).shell_paths;
        (upright ? root_shells : upper_shells) += shells;
        if (upright)
            continue;
