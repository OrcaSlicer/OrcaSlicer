size_t count_lines_starting(const std::string &gcode, const std::string &prefix)
{
    std::istringstream in(gcode);
    std::string        line;
    size_t             n = 0;
    while (std::getline(in, line))
        if (line.rfind(prefix, 0) == 0) ++ n;
    return n;
}

void visit_paths(const PrintObject &obj, const std::function<void(const ExtrusionPath &, const Layer &)> &fn)
{
    std::function<void(const ExtrusionEntity *, const Layer *)> visit = [&](const ExtrusionEntity *e, const Layer *layer) {
        if (const auto *cc = dynamic_cast<const ExtrusionEntityCollection *>(e)) { for (auto *x : cc->entities) visit(x, layer); return; }
        if (const auto *p = dynamic_cast<const ExtrusionPath *>(e)) fn(*p, *layer);
        else if (const auto *mp = dynamic_cast<const ExtrusionMultiPath *>(e)) for (const ExtrusionPath &p : mp->paths) fn(p, *layer);
        else if (const auto *lp = dynamic_cast<const ExtrusionLoop *>(e)) for (const ExtrusionPath &p : lp->paths) fn(p, *layer);
    };
    for (const Layer *layer : obj.layers())
        for (const LayerRegion *lr : layer->regions()) { visit(&lr->fills, layer); visit(&lr->perimeters, layer); }
}
