using HeightFn = std::function<double(double, double)>;

// A block over [-a, a] x [-b, b] whose top is z = f(x, y), as a closed mesh: an n x m grid on top,
// four walls and a flat bottom at z = 0.
TriangleMesh heightfield_block(double a, double b, int n, int m, const HeightFn &f)
{
    indexed_triangle_set its;
    auto top = [&](int i, int j) { return int(j * (n + 1) + i); };
    for (int j = 0; j <= m; ++ j)
        for (int i = 0; i <= n; ++ i) {
            const double x = -a + 2. * a * i / n, y = -b + 2. * b * j / m;
            its.vertices.emplace_back(float(x), float(y), float(f(x, y)));
        }
    const int base = int(its.vertices.size());
    for (int j = 0; j <= m; ++ j)
        for (int i = 0; i <= n; ++ i) {
            const double x = -a + 2. * a * i / n, y = -b + 2. * b * j / m;
            its.vertices.emplace_back(float(x), float(y), 0.f);
        }
    auto bot = [&](int i, int j) { return base + top(i, j); };
    for (int j = 0; j < m; ++ j)
        for (int i = 0; i < n; ++ i) {
            its.indices.emplace_back(top(i, j), top(i + 1, j), top(i + 1, j + 1));
            its.indices.emplace_back(top(i, j), top(i + 1, j + 1), top(i, j + 1));
            its.indices.emplace_back(bot(i, j), bot(i + 1, j + 1), bot(i + 1, j));
            its.indices.emplace_back(bot(i, j), bot(i, j + 1), bot(i + 1, j + 1));
        }
    // walls: y = -b (j = 0), y = +b (j = m), x = -a (i = 0), x = +a (i = n); outward normals
    for (int i = 0; i < n; ++ i) {
        its.indices.emplace_back(bot(i, 0), bot(i + 1, 0), top(i + 1, 0));
        its.indices.emplace_back(bot(i, 0), top(i + 1, 0), top(i, 0));
        its.indices.emplace_back(bot(i + 1, m), bot(i, m), top(i, m));
        its.indices.emplace_back(bot(i + 1, m), top(i, m), top(i + 1, m));
    }
    for (int j = 0; j < m; ++ j) {
        its.indices.emplace_back(bot(0, j + 1), bot(0, j), top(0, j));
        its.indices.emplace_back(bot(0, j + 1), top(0, j), top(0, j + 1));
        its.indices.emplace_back(bot(n, j), bot(n, j + 1), top(n, j + 1));
        its.indices.emplace_back(bot(n, j), top(n, j + 1), top(n, j));
    }
    return TriangleMesh(std::move(its));
}

constexpr double kH = 0.2;

DynamicPrintConfig base_config(bool on)
{
    DynamicPrintConfig config = DynamicPrintConfig::full_print_config();
    config.set_deserialize_strict({
        { "layer_height", kH },
        { "initial_layer_print_height", kH },
        { "top_shell_layers", 4 },
        { "bottom_shell_layers", 2 },
        { "wall_loops", 2 },
        { "sparse_infill_density", "15%" },
        { "enable_arc_fitting", 0 },
        { "use_relative_e_distances", 1 },
        { "layer_change_gcode", "G92 E0" },
        { "nonplanar_layers", on ? 1 : 0 },
        { "nonplanar_max_angle", 12 },
        { "nonplanar_max_height", 5 },
    });
    return config;
}

struct Sliced
{
    Model       model;
    Print       print;
    std::string gcode;
};

void slice(Sliced &s, TriangleMesh mesh, const DynamicPrintConfig &config)
{
    std::vector<TriangleMesh> meshes;
    meshes.emplace_back(std::move(mesh));
    Test::init_print(std::move(meshes), s.print, s.model, config);
    s.print.process();
    s.gcode = Test::gcode(s.print);
}

// G-code minus the settings block lines that name the new keys (every new key shows up there).
void dump(const std::string &name, const std::string &gcode)
{
    if (const char *dir = std::getenv("NPTOP_DUMP"))
        std::ofstream(std::string(dir) + "/" + name + ".gcode") << gcode;
}

std::string strip_np_config(const std::string &gcode)
{
    std::istringstream in(gcode);
    std::string        line, out;
    while (std::getline(in, line))
        // The object label ids differ between any two prints in one process (pre-existing).
        if (line.find("nonplanar_") == std::string::npos && line.find("printing object") == std::string::npos &&
            line.rfind("; generated by", 0) != 0) // timestamp
            out += line + "\n";
    return out;
}

struct LayerScan
{
    size_t shell_paths      = 0;
    double max_shell_err    = 0.;   // max |top curved z - surface|
    double max_above        = -1e9; // max (extrusion z - surface) in the core
    double max_stair_excess = -1e9; // max (planar print_z - (S - T + h/2)) in the core
    size_t top_samples      = 0;
    double ex_x = 0, ex_y = 0, ex_z = 0; int ex_role = 0;
};

// Walks every extrusion of the object. `core(x, y)` selects points well inside the patch.
LayerScan scan_layers(const PrintObject &obj, const HeightFn &f, const std::function<bool(double, double)> &core, double T, double zcap = 1e9)
{
    LayerScan r;
    // slice frame -> mesh frame: the object is centred on its bounding box.
    BoundingBox bb;
    for (const ExPolygon &ex : obj.layers().front()->lslices) bb.merge(get_extents(ex.contour));
    const Vec2d c = unscale(bb.center());
    std::function<void(const ExtrusionEntity *, const Layer *)> visit = [&](const ExtrusionEntity *e, const Layer *layer) {
        if (const auto *coll = dynamic_cast<const ExtrusionEntityCollection *>(e)) {
            for (const ExtrusionEntity *x : coll->entities) visit(x, layer);
            return;
        }
        std::vector<const ExtrusionPath *> paths;
        if (const auto *p = dynamic_cast<const ExtrusionPath *>(e)) paths.push_back(p);
        else if (const auto *mp = dynamic_cast<const ExtrusionMultiPath *>(e)) for (const ExtrusionPath &p : mp->paths) paths.push_back(&p);
        else if (const auto *lp = dynamic_cast<const ExtrusionLoop *>(e)) for (const ExtrusionPath &p : lp->paths) paths.push_back(&p);
        for (const ExtrusionPath *p : paths) {
            if (p->nonplanar_shell) ++ r.shell_paths;
            std::vector<Vec3d> samples;
            const Points3 &pts = p->polyline.points;
            for (size_t i = 0; i < pts.size(); ++ i) {
                const Vec3d a(unscale<double>(pts[i].x()), unscale<double>(pts[i].y()), unscale<double>(pts[i].z()));
                if (i + 1 == pts.size()) { samples.push_back(a); break; }
                const Vec3d b(unscale<double>(pts[i + 1].x()), unscale<double>(pts[i + 1].y()), unscale<double>(pts[i + 1].z()));
                const int   ns = std::max(1, int(std::ceil((b - a).head<2>().norm() / 0.2)));
                for (int k = 0; k < ns; ++ k) samples.push_back(a + (b - a) * (double(k) / ns));
            }
            for (const Vec3d &pt : samples) {
                const double x = pt.x() - c.x(), y = pt.y() - c.y();
                if (! core(x, y))
                    continue;
                const double s = f(x, y);
                const double z = layer->print_z + pt.z();
                if (z > zcap) continue; // material of another top over this one
                r.max_above = std::max(r.max_above, z - s);
                if (p->nonplanar_shell) {
                    if (z > s - 0.5 * kH) { // the visible (last) curved layer
                        r.max_shell_err = std::max(r.max_shell_err, std::abs(z - s));
                        ++ r.top_samples;
                    }
                } else
                {
                    const double ex = layer->print_z - (s - T + 0.5 * kH);
                    if (ex > r.max_stair_excess) { r.max_stair_excess = ex; r.ex_x = x; r.ex_y = y; r.ex_z = layer->print_z; r.ex_role = int(p->role()); }
                }
            }
        }
    };
    for (const Layer *layer : obj.layers())
        for (const LayerRegion *lr : layer->regions()) {
            visit(&lr->fills, layer);
            visit(&lr->perimeters, layer);
        }
    return r;
}

double max_extrusion_z(const std::string &gcode)
{
    std::istringstream in(gcode);
    std::string        line;
    double             z = 0., zmax = 0.;
    const std::regex   num(R"(([XYZE])(-?\d*\.?\d+))");
    while (std::getline(in, line)) {
        if (line.rfind("G1", 0) != 0)
            continue;
        const std::string code = line.substr(0, line.find(';'));
        bool   xy = false;
        double e  = 0.;
        for (std::sregex_iterator it(code.begin(), code.end(), num), end; it != end; ++ it) {
            const char   a = (*it)[1].str()[0];
            const double v = std::stod((*it)[2].str());
            if (a == 'Z') z = v;
            if (a == 'X' || a == 'Y') xy = true;
            if (a == 'E') e = v;
        }
        if (xy && e > 0.)
            zmax = std::max(zmax, z);
    }
    return zmax;
}

