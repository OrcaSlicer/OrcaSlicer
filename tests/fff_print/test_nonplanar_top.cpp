// Collects every extrusion sample within `r` mm (XY) of (x, y), mesh frame: (z, role, shell).
std::vector<std::tuple<double, int, bool>> samples_near(const PrintObject &obj, double x, double y, double r)
{
    BoundingBox bb;
    for (const ExPolygon &ex : obj.layers().front()->lslices) bb.merge(get_extents(ex.contour));
    const Vec2d c = unscale(bb.center());
    std::vector<std::tuple<double, int, bool>> out;
    std::function<void(const ExtrusionEntity *, const Layer *)> visit = [&](const ExtrusionEntity *e, const Layer *layer) {
        if (const auto *cc = dynamic_cast<const ExtrusionEntityCollection *>(e)) { for (auto *q : cc->entities) visit(q, layer); return; }
        std::vector<const ExtrusionPath *> paths;
        if (const auto *p = dynamic_cast<const ExtrusionPath *>(e)) paths.push_back(p);
        else if (const auto *mp = dynamic_cast<const ExtrusionMultiPath *>(e)) for (const ExtrusionPath &p : mp->paths) paths.push_back(&p);
        else if (const auto *lp = dynamic_cast<const ExtrusionLoop *>(e)) for (const ExtrusionPath &p : lp->paths) paths.push_back(&p);
        for (const ExtrusionPath *p : paths) {
            const Points3 &pts = p->polyline.points;
            for (size_t i = 0; i + 1 < pts.size(); ++ i) {
                const Vec3d a(unscale<double>(pts[i].x()), unscale<double>(pts[i].y()), unscale<double>(pts[i].z()));
                const Vec3d b(unscale<double>(pts[i + 1].x()), unscale<double>(pts[i + 1].y()), unscale<double>(pts[i + 1].z()));
                const int ns = std::max(1, int(std::ceil((b - a).head<2>().norm() / 0.05)));
                for (int k = 0; k <= ns; ++ k) {
                    const Vec3d q = a + (b - a) * (double(k) / ns);
                    if (Vec2d(q.x() - c.x() - x, q.y() - c.y() - y).norm() <= r)
                        out.emplace_back(layer->print_z + q.z(), int(p->role()), p->nonplanar_shell);
                }
            }
        }
    };
    for (const Layer *layer : obj.layers())
        for (const LayerRegion *lr : layer->regions()) { visit(&lr->fills, layer); visit(&lr->perimeters, layer); }
    return out;
}

// Curved layers over (x, y): distinct depths of the shell samples below the surface, in layers.
int curved_layers_at(const PrintObject &obj, const HeightFn &f, double x, double y)
{
    std::set<int> depths;
    for (const auto &[z, role, shell] : samples_near(obj, x, y, 0.3))
        if (shell)
            depths.insert(int(std::lround((f(x, y) - z) / kH)));
    return int(depths.size());
}

// Solid layers (top, internal solid or internal bridge infill) stacked under the top at (x, y) in a planar slice.
int planar_solid_layers_at(const PrintObject &obj, double x, double y)
{
    std::map<long, std::set<int>> roles_by_z; // layer z (um) -> roles there
    for (const auto &[z, role, shell] : samples_near(obj, x, y, 0.3))
        roles_by_z[std::lround(z * 1000.)].insert(role);
    int  n      = 0;
    bool in_top = false;
    for (auto it = roles_by_z.rbegin(); it != roles_by_z.rend(); ++ it) {
        // On a stair the sample radius can catch the next step's wall above this point's top surface:
        // the shell starts at the highest layer with top solid infill here.
        if (! in_top) {
            if (! it->second.count(int(erTopSolidInfill)))
                continue;
            in_top = true;
        }
        // the bottom layer of a planar top shell over sparse infill is an internal bridge
        const bool solid = it->second.count(int(erTopSolidInfill)) || it->second.count(int(erSolidInfill)) ||
                           it->second.count(int(erInternalBridgeInfill));
        if (! solid)
            break;
        ++ n;
    }
    return n;
}
