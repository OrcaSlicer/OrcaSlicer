struct TempTree
{
    fs::path path;
    TempTree()
    {
        path = fs::temp_directory_path() / fs::unique_path("other-slicers-%%%%-%%%%");
        fs::create_directories(path);
    }
    ~TempTree()
    {
        boost::system::error_code ec;
        fs::remove_all(path, ec);
    }
};

void write_file(const fs::path &p, const std::string &text)
{
    fs::create_directories(p.parent_path());
    boost::nowide::ofstream out(p.string(), std::ios::binary);
    out << text;
}

// An OrcaSlicer data directory: one installed vendor ("OrcaFilamentLibrary") with a two-level
// filament chain and a printer, and the person's own presets.
void make_orca(const fs::path &dir)
{
    write_file(dir / "system" / "Lib.json", R"({"name":"Lib","filament_list":[
        {"name":"fdm_filament_pla","sub_path":"filament/base/fdm_filament_pla.json"},
        {"name":"Generic PLA @System","sub_path":"filament/Generic PLA @System.json"}],
        "machine_list":[{"name":"Lib Printer 0.4 nozzle","sub_path":"machine/Lib Printer 0.4 nozzle.json"}]})");
    write_file(dir / "system" / "Lib" / "filament" / "base" / "fdm_filament_pla.json",
               R"({"type":"filament","name":"fdm_filament_pla","instantiation":"false","nozzle_temperature":["210"],
                   "filament_type":["PLA"],"hot_plate_temp":["60"]})");
    write_file(dir / "system" / "Lib" / "filament" / "Generic PLA @System.json",
               R"({"type":"filament","name":"Generic PLA @System","inherits":"fdm_filament_pla","from":"system",
                   "setting_id":"GFSL99","filament_id":"GFL99","instantiation":"true","nozzle_temperature":["215"]})");
    write_file(dir / "system" / "Lib" / "machine" / "Lib Printer 0.4 nozzle.json",
               R"({"type":"machine","name":"Lib Printer 0.4 nozzle","instantiation":"true","nozzle_diameter":["0.4"],
                   "printable_area":["0x0","200x0","200x200","0x200"],"printer_model":"Lib Printer"})");

    const fs::path user = dir / "user" / "default";
    write_file(user / "filament" / "My PLA.json",
               R"({"name":"My PLA","inherits":"Generic PLA @System","from":"User","version":"2.3.0.4",
                   "filament_settings_id":["My PLA"],"filament_flow_ratio":["0.95"],
                   "compatible_printers":["My Printer","Gone Printer","Lib Printer 0.4 nozzle"]})");
    write_file(user / "machine" / "My Printer.json",
               R"({"name":"My Printer","inherits":"Lib Printer 0.4 nozzle","from":"User","version":"2.3.0.4",
                   "printer_settings_id":"My Printer","print_host":"192.0.2.20","printhost_apikey":"SECRET-KEY",
                   "printable_height":"250"})");
    write_file(user / "process" / "Orphan.json",
               R"({"name":"Orphan","inherits":"0.20mm Nowhere @Lib","from":"User","print_settings_id":"Orphan","layer_height":"0.3"})");
    // A bundle, not the person's own presets.
    write_file(dir / "user" / "default" / "_local" / "x" / "filament" / "Bundle PLA.json", R"({"name":"Bundle PLA"})");
    write_file(dir / "user" / "_local" / "filament" / "Bundle PLA.json", R"({"name":"Bundle PLA"})");
}

struct FakeTarget
{
    std::map<Kind, std::set<std::string>> system, user;
    Target target()
    {
        Target t;
        t.name_taken = [this](Kind k, const std::string &n) { return system[k].count(n) > 0 || user[k].count(n) > 0; };
        t.has_system = [this](Kind k, const std::string &n) { return system[k].count(n) > 0; };
        return t;
    }
};

const Planned *find_item(const Plan &plan, const std::string &source_name)
{
    for (const Planned &item : plan.items)
        if (item.source.name == source_name)
            return &item;
    return nullptr;
}

const Skipped *find_skipped(const Plan &plan, const std::string &source_name)
{
    for (const Skipped &s : plan.skipped)
        if (s.name == source_name)
            return &s;
    return nullptr;
}

