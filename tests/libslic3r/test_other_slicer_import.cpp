// Unlayered's shipped vendor profiles, for the built-in selections.
struct FakeShipped : FakeTarget
{
    std::map<std::string, std::string> filament_vendors; // name -> vendor
    std::set<std::string>              enabled_filaments;
    VendorModels                       shipped, enabled;
    bool                               fresh{false};
    Target target()
    {
        Target t           = FakeTarget::target();
        t.shipped_models   = shipped;
        t.enabled_models   = enabled;
        t.filament_vendor  = [this](const std::string &n) { auto it = filament_vendors.find(n); return it == filament_vendors.end() ? std::string() : it->second; };
        t.filament_enabled = [this](const std::string &n) { return enabled_filaments.count(n) > 0; };
        t.fresh            = fresh;
        return t;
    }
};

