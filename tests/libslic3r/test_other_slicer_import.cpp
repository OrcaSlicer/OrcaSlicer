    CHECK(printer->config.dump().find("TOPSECRET") == std::string::npos);
    CHECK(printer->dropped_connection);
    REQUIRE(find_skipped(p, "Office MK4") != nullptr);
    CHECK(find_skipped(p, "Office MK4")->why == Skipped::Why::NoPrinter);
