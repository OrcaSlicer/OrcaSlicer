namespace {

// The per-user application data directory find() looks in, made under `root` for this platform.
fs::path user_data_root(const fs::path &root)
{
#if defined(_WIN32)
    return root / "Roaming";
#elif defined(__APPLE__)
    return root / "home" / "Library" / "Application Support";
#else
    return root / "config";
#endif
}

// Points find() at `root` for the duration of the test.
struct ScopedUserDirs
{
    std::vector<std::pair<std::string, std::string>> saved;
    explicit ScopedUserDirs(const fs::path &root)
    {
        set("APPDATA", (root / "Roaming").string());
        set("HOME", (root / "home").string());
        set("XDG_CONFIG_HOME", (root / "config").string());
    }
    ~ScopedUserDirs()
    {
        for (const auto &[k, v] : saved)
            put(k, v);
    }
    void set(const std::string &k, const std::string &v)
    {
        const char *old = boost::nowide::getenv(k.c_str());
        saved.emplace_back(k, old ? old : "");
        put(k, v);
    }
    // Through nowide, which is how the importer reads them (env_path) on every platform.
    static void put(const std::string &k, const std::string &v) { boost::nowide::setenv(k.c_str(), v.c_str(), 1); }
};

} // namespace

