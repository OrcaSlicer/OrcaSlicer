static const char* Segments_Vertex_Shader =
"#version 150\n"
"#define POINTY_CAPS\n"
"#define FIX_TWISTING\n"
"uniform vec3 light_top_dir;\n"
"uniform float gloss_strength;\n"
"const float light_top_diffuse = 0.6 * 0.8;\n"
// ORCA: the specular was 0.6 * 0.125, too faint to give the filament any sheen.
"const float light_top_specular = 0.6 * 0.25;\n"
"const float light_top_shininess = 20.0;\n"
"const vec3  light_front_dir = vec3(0.6985074, 0.1397015, 0.6985074);\n"
"const float light_front_diffuse = 0.6 * 0.2;\n"
"const float ambient = 0.2;\n"
"const float emission = 0.15;\n"
"const float REFERENCE_THICKNESS = 0.4;\n"
"const vec3 UP = vec3(0, 0, 1);\n"
"uniform mat4 view_matrix;\n"
"uniform mat4 projection_matrix;\n"
"uniform vec3 camera_position;\n"
"uniform samplerBuffer position_tex;\n"
"uniform samplerBuffer height_width_angle_tex;\n"
"uniform samplerBuffer color_tex;\n"
"uniform usamplerBuffer segment_index_tex;\n"
// ORCA: draw last segment first, so looking down the top layers hide the rest from the fragment shader.
"uniform bool reverse_order;\n"
"uniform int instances_count;\n"
// ORCA: section view
"uniform vec4 clipping_plane;\n"
"in int vertex_id;\n"
// ORCA: built with DEPTH_ONLY for the first order independent pass, the shaders keep the geometry and the joint cut
// but neither shade nor carry the colors, see ViewerImpl::render_translucent_segments()
"#ifndef DEPTH_ONLY\n"
"out vec3 color;\n"
"// ORCA: realistic view - the light the shadow map is able to block, kept apart from the\n"
"// ambient and emissive terms in color, which a shadow does not occlude. Their sum is the\n"
"// single lighting term this replaces, so shading is unchanged while shadows are off.\n"
"out vec3 color_direct;\n"
"#endif\n"
"// ORCA: realistic view - the fragment shader looks the fragment up in the shadow map, which\n"
"// needs its world position and, for the depth bias, its eye space normal.\n"
"out vec3 world_position;\n"
"#ifndef DEPTH_ONLY\n"
"out vec3 shadow_normal;\n"
"#endif\n"
// ORCA: section view - the segment and the light on its cut face
"flat out int segment_id;\n"
"#ifndef DEPTH_ONLY\n"
"out vec3 cut_color_direct;\n"
"#endif\n"
// ORCA: the opaque and the translucent segments are drawn in separate passes, see ViewerImpl::render_segments().
"uniform int first_instance;\n"
"flat out float alpha;\n"
// ORCA: the layers greyed or dimmed around the one the sliders show, see ViewerImpl::set_layer_colors().
"uniform ivec2 lit_layers;\n"
"uniform int grey_below_layer;\n"
"uniform float dim_brightness;\n"
"uniform int kept_vertex;\n"
"vec3 decode_color(vec3 color, int id, int layer) {\n"
"  vec3 rgb = round(255.0 * color);\n"
"  if (id != kept_vertex && layer != lit_layers.x && layer != lit_layers.y) {\n"
"    if (dim_brightness >= 0.0)\n"
"      rgb = floor(rgb * dim_brightness);\n"
"    else if (layer < grey_below_layer)\n"
"      rgb = vec3(64.0);\n"
"  }\n"
"  float f = 1.0 / 255.0f;\n"
"  return f * rgb;\n"
"}\n"
"float direct_lighting(vec3 eye_position, vec3 eye_normal) {\n"
"  float top_diffuse = light_top_diffuse * max(dot(eye_normal, light_top_dir), 0.0);\n"
"  float front_diffuse = light_front_diffuse * max(dot(eye_normal, light_front_dir), 0.0);\n"
"  float top_specular = light_top_specular * pow(max(dot(-normalize(eye_position), reflect(-light_top_dir, eye_normal)), 0.0), light_top_shininess);\n"
"  return top_diffuse + front_diffuse + top_specular;\n"
"}\n"
// ORCA: in realistic view, and on a translucent filament, the highlight is the fragment shader's, untinted
"float diffuse_lighting(vec3 eye_normal) {\n"
"  return light_top_diffuse * max(dot(eye_normal, light_top_dir), 0.0) + light_front_diffuse * max(dot(eye_normal, light_front_dir), 0.0);\n"
"}\n"
"void main() {\n"
"  int instance = first_instance + (reverse_order ? instances_count - 1 - gl_InstanceID : gl_InstanceID);\n"
"  int id_a = int(texelFetch(segment_index_tex, instance).r);\n"
"#ifdef DEPTH_ONLY\n"
"  alpha = 0.0;\n"
"#else\n"
"  alpha = texelFetch(color_tex, id_a).a;\n"
"#endif\n"
"  int id_b = id_a + 1;\n"
"  vec3 pos_a = texelFetch(position_tex, id_a).xyz;\n"
"  vec3 pos_b = texelFetch(position_tex, id_b).xyz;\n"
"  vec3 line = pos_b - pos_a;\n"
"  // directions of the line box in world space\n"
"  float line_len = length(line);\n"
"  vec3 line_dir;\n"
"  if (line_len < 1e-4)\n"
"    line_dir = vec3(1.0, 0.0, 0.0);\n"
"  else\n"
"    line_dir = line / line_len;\n"
"  vec3 line_right_dir;\n"
"  if (abs(dot(line_dir, UP)) > 0.9) {\n"
"    // For vertical lines, the width and height should be same, there is no concept of up and down.\n"
"    // For simplicity, the code will expand width in the x axis, and height in the y axis\n"
"    line_right_dir = normalize(cross(vec3(1, 0, 0), line_dir));\n"
"  }\n"
"  else\n"
"    line_right_dir = normalize(cross(line_dir, UP));\n"
"  vec3 line_up_dir = normalize(cross(line_right_dir, line_dir));\n"
// ORCA: the direction of the path across each joint, for the caps below; the fragment shader cuts the segment at
// its joints. The w of a position carries 0.5 at a joint, see extract_pos_and_or_hwa().
"  vec3 joint_prev = vec3(0.0);\n"
"  vec3 joint_next = vec3(0.0);\n"
"  if (alpha < 1.0 || gloss_strength > 0.0) {\n"
"    if (id_a > 0 && fract(texelFetch(position_tex, id_a).w) > 0.25) {\n"
"      vec3 prev = pos_a - texelFetch(position_tex, id_a - 1).xyz;\n"
// ORCA: past the vertex repeated in place that starts a split path
"      if (dot(prev, prev) < 1e-4 && id_a > 1)\n"
"        prev = pos_a - texelFetch(position_tex, id_a - 2).xyz;\n"
"      vec3 n = dot(prev, prev) > 1e-8 ? normalize(prev) + line_dir : vec3(0.0);\n"
"      if (dot(n, n) > 1e-4)\n"
"        joint_prev = prev;\n"
"    }\n"
"    if (id_b + 1 < textureSize(position_tex) && fract(texelFetch(position_tex, id_b).w) > 0.25) {\n"
"      vec3 next = texelFetch(position_tex, id_b + 1).xyz - pos_b;\n"
"      if (dot(next, next) < 1e-4 && id_b + 2 < textureSize(position_tex))\n"
"        next = texelFetch(position_tex, id_b + 2).xyz - pos_b;\n"
"      vec3 n = dot(next, next) > 1e-8 ? line_dir + normalize(next) : vec3(0.0);\n"
"      if (dot(n, n) > 1e-4)\n"
"        joint_next = next;\n"
"    }\n"
"  }\n"
"  const vec2 horizontal_vertical_view_signs_array[16] = vec2[](\n"
"    //horizontal view (from right)\n"
"    vec2(1.0, 0.0),\n"
"    vec2(0.0, 1.0),\n"
"    vec2(0.0, 0.0),\n"
"    vec2(0.0, -1.0),\n"
"    vec2(0.0, -1.0),\n"
"    vec2(1.0, 0.0),\n"
"    vec2(0.0, 1.0),\n"
"    vec2(0.0, 0.0),\n"
"    // vertical view (from top)\n"
"    vec2(0.0, 1.0),\n"
"    vec2(-1.0, 0.0),\n"
"    vec2(0.0, 0.0),\n"
"    vec2(1.0, 0.0),\n"
"    vec2(1.0, 0.0),\n"
"    vec2(0.0, 1.0),\n"
"    vec2(-1.0, 0.0),\n"
"    vec2(0.0, 0.0)\n"
"    );\n"
"  int id = vertex_id < 4 ? id_a : id_b;\n"
"  vec3 endpoint_pos = vertex_id < 4 ? pos_a : pos_b;\n"
"  vec4 hwa = texelFetch(height_width_angle_tex, id);\n"
"  vec3 height_width_angle = hwa.xyz;\n"
// ORCA: across the vertex repeated in place that starts a split path, a cut joint keeps no angle. The caps take
// it from the joint, to fill the outside of the turn as at any other joint.
"  vec3 joint_other = vertex_id < 4 ? joint_prev : joint_next;\n"
"  if (height_width_angle.z == 0.0 && dot(joint_other, joint_other) > 0.0) {\n"
"    vec3 into = vertex_id < 4 ? joint_other : line;\n"
"    vec3 onto = vertex_id < 4 ? line : joint_other;\n"
"    height_width_angle.z = atan(into.x * onto.y - into.y * onto.x, dot(into, onto));\n"
"  }\n"
"  // ORCA: Extract bias from w component\n"
"  float bias = hwa.w;\n"
"#ifdef FIX_TWISTING\n"
"  int closer_id = (dot(camera_position - pos_a, camera_position - pos_a) < dot(camera_position - pos_b, camera_position - pos_b)) ? id_a : id_b;\n"
"  vec3 closer_pos = (closer_id == id_a) ? pos_a : pos_b;\n"
"  vec3 camera_view_dir = normalize(closer_pos - camera_position);\n"
"  vec3 closer_height_width_angle = texelFetch(height_width_angle_tex, closer_id).xyz;\n"
"  vec3 diagonal_dir_border = normalize(closer_height_width_angle.x * line_up_dir + closer_height_width_angle.y * line_right_dir);\n"
"#else\n"
"  vec3 camera_view_dir = normalize(endpoint_pos - camera_position);\n"
"  vec3 diagonal_dir_border = normalize(height_width_angle.x * line_up_dir + height_width_angle.y * line_right_dir);\n"
"#endif\n"
// ORCA: a filament's opacity is that of REFERENCE_THICKNESS mm of it, here the path of the view ray through the extrusion
"#ifndef DEPTH_ONLY\n"
"  if (alpha < 1.0) {\n"
"    vec2 hw = texelFetch(height_width_angle_tex, id_a).xy;\n"
"    float path = 1.0 / max(abs(dot(camera_view_dir, line_up_dir)) / hw.x + abs(dot(camera_view_dir, line_right_dir)) / hw.y, 1e-3);\n"
// ORCA: below 1, which would take a translucent segment for an opaque one
"    alpha = min(1.0 - pow(1.0 - alpha, min(path / REFERENCE_THICKNESS, 16.0)), 0.999);\n"
"  }\n"
"#endif\n"
"  bool is_vertical_view = abs(dot(camera_view_dir, line_up_dir)) / abs(dot(diagonal_dir_border, line_up_dir)) >\n"
"    abs(dot(camera_view_dir, line_right_dir)) / abs(dot(diagonal_dir_border, line_right_dir));\n"
"  vec2 signs = horizontal_vertical_view_signs_array[vertex_id + 8 * int(is_vertical_view)];\n"
"#ifndef POINTY_CAPS\n"
"  if (vertex_id == 2 || vertex_id == 7) signs = -horizontal_vertical_view_signs_array[(vertex_id - 2) + 8 * int(is_vertical_view)];\n"
"#endif\n"
"  float view_right_sign = sign(dot(-camera_view_dir, line_right_dir));\n"
"  float view_top_sign = sign(dot(-camera_view_dir, line_up_dir));\n"
"  float half_height = 0.5 * height_width_angle.x;\n"
"  float half_width = 0.5 * height_width_angle.y;\n"
"  vec3 horizontal_dir = half_width * line_right_dir;\n"
"  vec3 vertical_dir = half_height * line_up_dir;\n"
"  float horizontal_sign = signs.x * view_right_sign;\n"
"  float vertical_sign = signs.y * view_top_sign;\n"
"  vec3 pos = endpoint_pos + horizontal_sign * horizontal_dir + vertical_sign * vertical_dir;\n"
"  if (vertex_id == 2 || vertex_id == 7) {\n"
"    float line_dir_sign = (vertex_id == 2) ? -1.0 : 1.0;\n"
"    if (height_width_angle.z == 0) {\n"
"#ifdef POINTY_CAPS\n"
"      // There I add a cap to lines that do not have a following line\n"
"      // (or they have one, but perfectly aligned, so the cap is hidden inside the next line).\n"
"      pos += line_dir_sign * line_dir * half_width;\n"
"#endif\n"
"    }\n"
"    else {\n"
"      pos += line_dir_sign * line_dir * half_width * sin(abs(height_width_angle.z) * 0.5);\n"
"      pos += sign(height_width_angle.z) * horizontal_dir * cos(abs(height_width_angle.z) * 0.5);\n"
"    }\n"
"  }\n"
"  vec3 eye_position = (view_matrix * vec4(pos, 1.0)).xyz;\n"
"  // ORCA: Apply bias to z-position to avoid z-fighting\n"
"  eye_position.z += bias;\n"
"  world_position = pos;\n"
"  segment_id = id_a;\n"
"#ifndef DEPTH_ONLY\n"
"  vec3 eye_normal = (view_matrix * vec4(normalize(pos - endpoint_pos), 0.0)).xyz;\n"
"  vec3 color_base = decode_color(texelFetch(color_tex, id).rgb, id, int(texelFetch(position_tex, id).w));\n"
"  color = color_base * (ambient + emission);\n"
"  color_direct = color_base * ((alpha < 1.0 || gloss_strength > 0.0) ? diffuse_lighting(eye_normal) : direct_lighting(eye_position, eye_normal));\n"
"  shadow_normal = eye_normal;\n"
"  cut_color_direct = clipping_plane.xyz == vec3(0.0) ? vec3(0.0) :\n"
"    color_base * ((alpha < 1.0 || gloss_strength > 0.0) ? diffuse_lighting(mat3(view_matrix) * -clipping_plane.xyz) :\n"
"                                direct_lighting(eye_position, mat3(view_matrix) * -clipping_plane.xyz));\n"
"#endif\n"
"  gl_Position = projection_matrix * vec4(eye_position, 1.0);\n"
"}\n";

// ORCA: realistic view - shadow caster, one light facing ribbon per segment, not instanced as tiny instances are slow.
static const char* Segments_Shadow_Caster_Vertex_Shader =
"#version 150\n"
"const vec3 UP = vec3(0, 0, 1);\n"
"const int CORNERS[6] = int[](0, 1, 2, 0, 2, 3);\n"
"uniform mat4 view_matrix;\n"
"uniform mat4 projection_matrix;\n"
"uniform samplerBuffer position_tex;\n"
"uniform samplerBuffer height_width_angle_tex;\n"
"uniform usamplerBuffer segment_index_tex;\n"
"uniform bool reverse_order;\n"
"uniform int instances_count;\n"
"out vec3 world_position;\n"
"uniform samplerBuffer color_tex;\n"
"flat out float alpha;\n"
"flat out int segment_id;\n"
"void main() {\n"
"  int segment = gl_VertexID / 6;\n"
"  int corner = CORNERS[gl_VertexID - 6 * segment];\n"
"  int instance = reverse_order ? instances_count - 1 - segment : segment;\n"
"  int id_a = int(texelFetch(segment_index_tex, instance).r);\n"
"  alpha = texelFetch(color_tex, id_a).a;\n"
"  segment_id = id_a;\n"
"  int id = corner < 2 ? id_a : id_a + 1;\n"
"  vec3 pos_a = texelFetch(position_tex, id_a).xyz;\n"
"  vec3 pos_b = texelFetch(position_tex, id_a + 1).xyz;\n"
"  vec3 line = pos_b - pos_a;\n"
"  float line_len = length(line);\n"
"  vec3 line_dir = line_len < 1e-4 ? vec3(1.0, 0.0, 0.0) : line / line_len;\n"
"  vec3 line_right_dir = abs(dot(line_dir, UP)) > 0.9 ? normalize(cross(vec3(1, 0, 0), line_dir)) : normalize(cross(line_dir, UP));\n"
"  vec3 line_up_dir = normalize(cross(line_right_dir, line_dir));\n"
"  vec3 to_light = vec3(view_matrix[0][2], view_matrix[1][2], view_matrix[2][2]);\n"
"  vec3 side_dir = cross(to_light, line_dir);\n"
"  side_dir = dot(side_dir, side_dir) < 1e-8 ? line_right_dir : normalize(side_dir);\n"
"  vec2 height_width = texelFetch(height_width_angle_tex, id).xy;\n"
"  float half_extent = 0.5 * (height_width.y * abs(dot(line_right_dir, side_dir)) + height_width.x * abs(dot(line_up_dir, side_dir)));\n"
"  float along = (corner < 2 ? -0.5 : 0.5) * height_width.y;\n"
"  float side = (corner == 0 || corner == 3) ? -1.0 : 1.0;\n"
"  vec3 pos = (corner < 2 ? pos_a : pos_b) + along * line_dir + side * half_extent * side_dir;\n"
"  world_position = pos;\n"
"  gl_Position = projection_matrix * (view_matrix * vec4(pos, 1.0));\n"
"}\n";

// ORCA: realistic view - the shadow caster writes depth only. What a section cuts away casts no shadow.
static const char* Segments_Shadow_Caster_Fragment_Shader =
"#version 150\n"
"uniform vec4 clipping_plane;\n"
"in vec3 world_position;\n"
"flat in float alpha;\n"
"flat in int segment_id;\n"
// ORCA: a translucent segment covers a share of the texels as large as its opacity, in an ordered pattern the
// receivers' 5x5 filter reads as a lighter shadow. The pattern moves with the segment, so stacked layers add up.
"const float BAYER[16] = float[](0.0, 8.0, 2.0, 10.0, 12.0, 4.0, 14.0, 6.0, 3.0, 11.0, 1.0, 9.0, 15.0, 7.0, 13.0, 5.0);\n"
"void main() {\n"
"  if (dot(vec4(world_position, 1.0), clipping_plane) < 0.0)\n"
"    discard;\n"
"  ivec2 cell = (ivec2(gl_FragCoord.xy) + ivec2(segment_id, segment_id >> 2)) & 3;\n"
"  if (alpha < 1.0 && (BAYER[4 * cell.y + cell.x] + 0.5) / 16.0 > alpha)\n"
"    discard;\n"
"}\n";

static const char* Segments_Fragment_Shader =
"#version 150\n"
"// ORCA: realistic view - object-on-object and self shadows, read from the same depth map the\n"
"// rest of the 3D scene samples. shadow_intensity == 0, the default, short-circuits the lookup,\n"
"// so the toolpaths shade exactly as before whenever realistic view is off.\n"
"uniform vec3 light_top_dir;\n"
"uniform sampler2D shadow_map;\n"
"uniform mat4 shadow_light_vp;\n"
"uniform float shadow_intensity;\n"
"uniform float shadow_map_texel;\n"
// ORCA: the lighting term peaks near 0.9 and every later multiplier - the shadow, then the SSAO
// post pass - only takes more light away, so the print reads dimmer and duller than the legend
// colours. These pay that back. Both are 1.0 for an untouched image; what the caller actually
// passes in each mode is decided in GLCanvas3D::_render_gcode, not here.
"uniform float exposure;\n"
"uniform float saturation;\n"
// ORCA: section view - only camera-facing faces are drawn, so cut faces are ray cast
"uniform vec4 clipping_plane;\n"
"uniform mat4 view_matrix;\n"
"uniform mat4 projection_matrix;\n"
"uniform vec3 camera_position;\n"
"uniform samplerBuffer position_tex;\n"
"uniform samplerBuffer height_width_angle_tex;\n"
"const vec3 UP = vec3(0, 0, 1);\n"
"const vec3 LUMA = vec3(0.2126, 0.7152, 0.0722);\n"
// ORCA: in realistic view every filament is glossy, with an untinted highlight a translucent one's opacity does not dim
"uniform float gloss_strength;\n"
"const float GLOSS_SHININESS = 80.0;\n"
"#ifndef DEPTH_ONLY\n"
"in vec3 color;\n"
"in vec3 color_direct;\n"
"#endif\n"
"in vec3 world_position;\n"
"#ifndef DEPTH_ONLY\n"
"in vec3 shadow_normal;\n"
"#endif\n"
"flat in int segment_id;\n"
"#ifndef DEPTH_ONLY\n"
"in vec3 cut_color_direct;\n"
"#endif\n"
"flat in float alpha;\n"
"out vec4 fragment_color;\n"
// ORCA: order independent transparency, see ViewerImpl::render_translucent_segments(). Pass 1 finds the depth of
// the nearest translucent surface, pass 2 sets that surface apart and adds up the weighted others.
"out float oit_reveal;\n"
"out vec4 oit_front;\n"
"#ifdef DEPTH_ONLY\n"
"const int oit_pass = 1;\n"
"#else\n"
"uniform int oit_pass;\n"
"#endif\n"
"uniform sampler2D opaque_depth;\n"
"uniform sampler2D front_depth;\n"
"uniform vec2 oit_depth_range;\n"
"float shadow_shade(vec3 position, vec3 normal) {\n"
"  if (shadow_intensity <= 0.0)\n"
"    return 1.0;\n"
"  vec4 lp = shadow_light_vp * vec4(position, 1.0);\n"
"  vec3 proj = lp.xyz / lp.w;\n"
"  proj = proj * 0.5 + 0.5;\n"
"  if (proj.z > 1.0)\n"
"    return 1.0;\n"
"  // Slope-scaled bias, as in gouraud.fs. An extrusion is only a handful of shadow-map texels\n"
"  // wide, so grazing faces need the larger bias to keep self-shadow acne off the top surfaces.\n"
"  float NdotL = dot(normalize(normal), light_top_dir);\n"
"  float bias = mix(0.0004, 0.004, clamp(1.0 - NdotL, 0.0, 1.0));\n"
"  float sum = 0.0;\n"
"  for (int x = -2; x <= 2; ++x) {\n"
"    for (int y = -2; y <= 2; ++y) {\n"
"      float closest = texture(shadow_map, proj.xy + vec2(float(x), float(y)) * shadow_map_texel).r;\n"
"      sum += (proj.z - bias > closest) ? 1.0 : 0.0;\n"
"    }\n"
"  }\n"
"  return 1.0 - shadow_intensity * (sum / 25.0);\n"
"}\n"
// ORCA: section view - where the view ray meets the plane, if inside the extrusion's diamond section
"bool find_cut(out vec3 cut) {\n"
// parallel rays for an orthographic projection
"  vec3 ray = projection_matrix[3][3] == 1.0 ? -vec3(view_matrix[0][2], view_matrix[1][2], view_matrix[2][2]) :\n"
"                                             normalize(world_position - camera_position);\n"
"  float approach = dot(clipping_plane.xyz, ray);\n"
"  if (approach <= 0.0)\n"
"    return false;\n"
"  cut = world_position - dot(vec4(world_position, 1.0), clipping_plane) / approach * ray;\n"
"  vec3 pos_a = texelFetch(position_tex, segment_id).xyz;\n"
"  vec3 line = texelFetch(position_tex, segment_id + 1).xyz - pos_a;\n"
"  float length_sq = dot(line, line);\n"
"  float along = length_sq < 1e-8 ? -1.0 : dot(cut - pos_a, line) / length_sq;\n"
"  if (along < 0.0 || along > 1.0)\n"
"    return false;\n"
"  vec3 line_dir = line * inversesqrt(length_sq);\n"
"  vec3 right_dir = abs(dot(line_dir, UP)) > 0.9 ? normalize(cross(vec3(1, 0, 0), line_dir)) : normalize(cross(line_dir, UP));\n"
"  vec3 offset = cut - pos_a - along * line;\n"
"  vec2 half_height_width = 0.5 * mix(texelFetch(height_width_angle_tex, segment_id).xy,\n"
"                                     texelFetch(height_width_angle_tex, segment_id + 1).xy, along);\n"
"  return abs(dot(offset, right_dir)) / half_height_width.y + abs(dot(offset, cross(right_dir, line_dir))) / half_height_width.x <= 1.0;\n"
"}\n"
// ORCA: two segments of a path overlap at their joint, which blending would draw twice and the highlight of
// realistic view shows on opaque ones too, so each is cut at the bisector plane of its joints: whether the
// fragment lies past the plane of the joint at vertex id, step being -1 for the start of the segment and 1 for
// its end, keeping 0.02 mm of overlap where the faces each segment turns to the camera would leave gaps without
// their caps. Past the vertex repeated in place that starts a split path, the neighbour is one vertex further.
"bool beyond_joint(int id, vec3 pos, vec3 line_dir, int step) {\n"
"  int size = textureSize(position_tex);\n"
"  if (id + step < 0 || id + step >= size || fract(texelFetch(position_tex, id).w) <= 0.25)\n"
"    return false;\n"
"  vec3 dir = float(step) * (texelFetch(position_tex, id + step).xyz - pos);\n"
"  if (dot(dir, dir) < 1e-4 && id + 2 * step >= 0 && id + 2 * step < size)\n"
"    dir = float(step) * (texelFetch(position_tex, id + 2 * step).xyz - pos);\n"
"  vec3 n = dot(dir, dir) > 1e-8 ? normalize(dir) + line_dir : vec3(0.0);\n"
"  return dot(n, n) > 1e-4 && float(step) * dot(normalize(n), world_position - pos) > 0.02;\n"
"}\n"
"void main() {\n"
"  if (alpha < 1.0 || gloss_strength > 0.0) {\n"
"    vec3 pos_a = texelFetch(position_tex, segment_id).xyz;\n"
"    vec3 pos_b = texelFetch(position_tex, segment_id + 1).xyz;\n"
"    vec3 line_dir = normalize(pos_b - pos_a);\n"
"    if (beyond_joint(segment_id, pos_a, line_dir, -1) || beyond_joint(segment_id + 1, pos_b, line_dir, 1))\n"
"      discard;\n"
"  }\n"
// ORCA: in the transparency passes, the opaque scene hides what lies behind it
"  if (oit_pass != 0 && gl_FragCoord.z > texelFetch(opaque_depth, ivec2(gl_FragCoord.xy), 0).r)\n"
"    discard;\n"
"  if (oit_pass == 1) {\n"
"    vec3 cut;\n"
"    if (dot(vec4(world_position, 1.0), clipping_plane) < 0.0 && !find_cut(cut))\n"
"      discard;\n"
"    fragment_color = vec4(gl_FragCoord.z);\n"
"    return;\n"
"  }\n"
"#ifndef DEPTH_ONLY\n"
"  vec3 c;\n"
"  vec3 position = world_position;\n"
"  vec3 normal = shadow_normal;\n"
"  bool cut_face = false;\n"
"  float shade;\n"
"  if (dot(vec4(world_position, 1.0), clipping_plane) >= 0.0) {\n"
"    shade = shadow_shade(position, normal);\n"
"    c = color + color_direct * shade;\n"
"  }\n"
"  else {\n"
"    if (!find_cut(position))\n"
"      discard;\n"
"    cut_face = true;\n"
"    normal = mat3(view_matrix) * -clipping_plane.xyz;\n"
"    shade = shadow_shade(position, normal);\n"
"    c = color + cut_color_direct * shade;\n"
"  }\n"
"  c *= exposure;\n"
"  c = mix(vec3(dot(c, LUMA)), c, saturation);\n"
// ORCA: the highlight takes the normal of the rounded extrusion the segment stands for, an ellipse of its height
// and width around its centre line, smooth across a joint, where the facets of two segments would catch it
// apart. It fades out towards the tip of a path end, whose normal runs along the extrusion.
"  float gloss = 0.0;\n"
"  if (gloss_strength > 0.0) {\n"
"    vec3 across = normalize(normal);\n"
"    vec3 start = texelFetch(position_tex, segment_id).xyz;\n"
"    vec3 line = texelFetch(position_tex, segment_id + 1).xyz - start;\n"
"    float length_sq = dot(line, line);\n"
"    if (!cut_face && length_sq > 1e-8) {\n"
"      float t = clamp(dot(position - start, line) / length_sq, 0.0, 1.0);\n"
"      vec2 half_height_width = 0.5 * mix(texelFetch(height_width_angle_tex, segment_id).xy, texelFetch(height_width_angle_tex, segment_id + 1).xy, t);\n"
"      vec3 radial = position - start - t * line;\n"
"      vec3 n = vec3(radial.xy / (half_height_width.y * half_height_width.y), radial.z / (half_height_width.x * half_height_width.x));\n"
"      n = dot(n, n) > 1e-12 ? normalize(n) : UP;\n"
"      across = mat3(view_matrix) * (n - dot(n, line) / length_sq * line);\n"
"    }\n"
"    vec3 v = projection_matrix[3][3] == 1.0 ? vec3(0.0, 0.0, 1.0) : -normalize((view_matrix * vec4(position, 1.0)).xyz);\n"
"    gloss = dot(across, across) > 1e-8 ? gloss_strength * dot(across, across) * pow(max(dot(v, reflect(-light_top_dir, normalize(across))), 0.0), GLOSS_SHININESS) * shade : 0.0;\n"
"  }\n"
"  if (alpha == 1.0) {\n"
"    fragment_color = vec4(clamp(c + gloss, 0.0, 1.0), 1.0);\n"
"    return;\n"
"  }\n"
// ORCA: translucent, premultiplied
"  fragment_color = vec4(clamp(c, 0.0, 1.0) * alpha + gloss, alpha);\n"
"  if (oit_pass != 2)\n"
"    return;\n"
"  if (gl_FragCoord.z <= texelFetch(front_depth, ivec2(gl_FragCoord.xy), 0).r) {\n"
"    oit_front = fragment_color;\n"
"    fragment_color = vec4(0.0);\n"
"    oit_reveal = 0.0;\n"
"    return;\n"
"  }\n"
"  float z = clamp((-(view_matrix * vec4(position, 1.0)).z - oit_depth_range.x) / (oit_depth_range.y - oit_depth_range.x), 0.0, 1.0);\n"
"  fragment_color *= alpha * max(pow(1.0 - z, 3.0), 1e-2);\n"
"  oit_reveal = -log(1.0 - alpha);\n"
"  oit_front = vec4(0.0);\n"
"#endif\n"
"}\n";

